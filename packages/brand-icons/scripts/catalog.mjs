import assert from 'node:assert/strict'

const safeId = /^[a-z0-9]+(?:[-_][a-z0-9]+)*$/
const groups = new Set(['model', 'provider', 'application'])
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0

/** Pure input validation and catalog generation, shared with fixture tests. */
export function collectBrands(metadata, lightFiles, darkFiles, aliases, darkColorIds) {
  assert.ok(Array.isArray(metadata) && metadata.length, 'Brand metadata must be a non-empty array')
  const labels = new Map()
  for (const brand of metadata) {
    assert.ok(safeId.test(brand.id), `Invalid brand ID: ${brand.id}`)
    assert.ok(typeof brand.label === 'string' && brand.label.trim(), `Missing label: ${brand.id}`)
    assert.ok(groups.has(brand.group), `Invalid group: ${brand.id}`)
    assert.ok(typeof brand.color === 'string' && brand.color, `Missing brand color: ${brand.id}`)
    assert.ok(!labels.has(brand.id), `Duplicate brand ID: ${brand.id}`)
    labels.set(brand.id, brand)
  }

  const light = new Set(lightFiles)
  const dark = new Set(darkFiles)
  const distinctDarkColors = darkColorIds ?? new Set(
    darkFiles.filter(file => file.endsWith('-color.png')).map(file => file.slice(0, -'-color.png'.length)),
  )
  const ids = new Set()
  for (const file of light) {
    if (!file.endsWith('.png')) continue
    if (/-(text-color|text-cn|text|brand-color|brand)\.png$/.test(file)) continue
    const id = file.replace(/(?:-color)?\.png$/, '')
    assert.ok(safeId.test(id), `Invalid asset name: ${file}`)
    assert.ok(labels.has(id), `Asset has no brand metadata: ${file}; update the metadata snapshot`)
    ids.add(id)
  }
  assert.ok(ids.size, 'No logo assets found')

  const entries = [...ids].map(id => {
    const brand = labels.get(id)
    return {
      id,
      label: brand.label,
      group: brand.group,
      color: brand.color,
      hasColor: light.has(`${id}-color.png`),
      hasDarkColor: light.has(`${id}-color.png`) && dark.has(`${id}-color.png`) && distinctDarkColors.has(id),
      hasDark: dark.has(`${id}.png`),
    }
  }).sort((a, b) => compare(a.label.toLowerCase(), b.label.toLowerCase()) || compare(a.id, b.id))

  assert.ok(aliases && typeof aliases === 'object' && !Array.isArray(aliases), 'Aliases must be an object')
  for (const [alias, target] of Object.entries(aliases)) {
    assert.ok(safeId.test(alias) && safeId.test(target), `Invalid alias: ${alias}`)
    assert.ok(!ids.has(alias), `Alias shadows a current brand: ${alias}`)
    assert.ok(ids.has(target), `Alias target is not a current brand: ${alias} -> ${target}`)
  }
  return entries
}

/** Persisted IDs must remain resolvable, either directly or through an alias. */
export function assertCompatible(previous, current, aliases, previousAliases = {}) {
  const ids = new Set(current.map(brand => brand.id))
  const resolve = id => ids.has(id) ? id : Object.hasOwn(aliases, id) && ids.has(aliases[id]) ? aliases[id] : undefined
  const removed = previous.filter(brand => !resolve(brand.id)).map(brand => brand.id)
  assert.equal(removed.length, 0, `Removed brand IDs need compatibility aliases: ${removed.join(', ')}`)
  const removedAliases = Object.keys(previousAliases).filter(alias => !resolve(alias))
  assert.equal(removedAliases.length, 0, `Removed historical aliases need compatibility mappings: ${removedAliases.join(', ')}`)
  const redirected = Object.entries(previousAliases)
    .filter(([alias, target]) => resolve(alias) !== resolve(target))
    .map(([alias, target]) => `${alias} (${target} -> ${resolve(alias)})`)
  assert.equal(redirected.length, 0, `Historical aliases changed brand: ${redirected.join(', ')}`)
}

export function renderAssets(entries) {
  const imports = []
  const records = []
  for (const [index, brand] of entries.entries()) {
    const prefix = `icon${index}`
    if (brand.hasColor) {
      imports.push(`import ${prefix}Color from '@lobehub/icons-static-png/light/${brand.id}-color.png'`)
      if (brand.hasDarkColor) imports.push(`import ${prefix}ColorDark from '@lobehub/icons-static-png/dark/${brand.id}-color.png'`)
      records.push(`  ${JSON.stringify(brand.id)}: { color: ${prefix}Color${brand.hasDarkColor ? `, colorDark: ${prefix}ColorDark` : ''} },`)
    } else {
      imports.push(`import ${prefix}Light from '@lobehub/icons-static-png/light/${brand.id}.png'`)
      if (brand.hasDark) imports.push(`import ${prefix}Dark from '@lobehub/icons-static-png/dark/${brand.id}.png'`)
      records.push(`  ${JSON.stringify(brand.id)}: { light: ${prefix}Light${brand.hasDark ? `, dark: ${prefix}Dark` : ''} },`)
    }
  }
  return `// Generated by pnpm generate:brand-icons. Do not edit.\nimport type { BrandIconAssets } from '../types'\n${imports.join('\n')}\n\nexport const brandIconAssets: Readonly<Record<string, BrandIconAssets>> = {\n${records.join('\n')}\n}\n`
}
