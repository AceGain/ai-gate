/** 默认图标：空串 = 自动（首字母 fallback） */
export const defaultProviderIcon = ''

/** 是否为自定义上传图标（data URL 或 http 链接，直接作为图片地址） */
export function isCustomIcon(icon: string): boolean {
  return icon.startsWith('data:') || icon.startsWith('http://') || icon.startsWith('https://')
}

/** 解析图标 URL：自定义图片原样返回；品牌 id（含旧 key 兼容）映射到 lobehub PNG；未知返回空串。无彩色的品牌按 isDark 取亮/暗单色变体 */
export function brandIconUrl(icon: string, isDark = false): string {
  if (!icon) return ''
  if (isCustomIcon(icon)) return icon
  const id = legacyBrandIconKeys[icon] ?? icon
  const entry = brandIcons[id]
  if (!entry) return ''
  return entry.color ?? (isDark ? entry.dark : entry.light) ?? ''
}
